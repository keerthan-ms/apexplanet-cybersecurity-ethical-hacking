class CrackTests(unittest.TestCase):
    def test_md5_wordlist_crack(self):
        target = hashlib.md5(b"password").hexdigest()
        self.assertEqual(target, "5f4dcc3b5aa765d61d8327deb882cf99")
        result = hc.crack_hash(target)
        self.assertTrue(result["found"])
        self.assertEqual(result["password"], "password")
        self.assertEqual(result["format"], "md5")
        self.assertEqual(result["status"], "cracked")
        self.assertGreaterEqual(result["attempts"], 1)
        self.assertLessEqual(result["attempts"], len(hc.DEFAULT_WORDLIST))
        self.assertGreaterEqual(result["seconds"], 0.0)

    def test_sha_family_cracks(self):
        for algorithm in ("sha1", "sha256", "sha512"):
            with self.subTest(algorithm=algorithm):
                target = hashlib.new(algorithm, b"letmein").hexdigest()
                result = hc.crack_hash(target)
                self.assertTrue(result["found"], result)
                self.assertEqual(result["password"], "letmein")
                self.assertEqual(result["format"], algorithm)

    def test_ntlm_needs_forced_format_and_cracks(self):
        target = hc.ntlm_hex("hunter2")
        auto = hc.crack_hash(target)
        self.assertEqual(auto["format_detected"], "md5")
        self.assertFalse(auto["found"])
        result = hc.crack_hash(target, "ntlm", source="forced")
        self.assertEqual(result["format"], "ntlm")
        self.assertEqual(result["format_source"], "forced")
        self.assertTrue(result["found"])
        self.assertEqual(result["password"], "hunter2")

    def test_bcrypt_crack(self):
        target = bcrypt.hashpw(b"letmein", bcrypt.gensalt(rounds=4))
        result = hc.crack_hash(target.decode("ascii"))
        self.assertEqual(result["format"], "bcrypt")
        self.assertTrue(result["found"])
        self.assertEqual(result["password"], "letmein")

    def test_sha512crypt_crack_at_minimum_rounds(self):
        target = hc.sha512_crypt_setting("dragon", "$6$rounds=1000$testsalt123")
        result = hc.crack_hash(target)
        self.assertEqual(result["format"], "sha512crypt")
        self.assertTrue(result["found"])
        self.assertEqual(result["password"], "dragon")

    def test_external_wordlist_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "extra.txt"
            path.write_text("unique-lab-passphrase\npassword\n",
                            encoding="utf-8")
            target = hashlib.md5(b"unique-lab-passphrase").hexdigest()
            result = hc.crack_hash(target, wordlist_path=str(path))
            self.assertEqual(result["wordlist"], str(path))
        self.assertTrue(result["found"])
        self.assertEqual(result["attempts"], 1)
        self.assertEqual(result["password"], "unique-lab-passphrase")

    def test_not_found_reports_full_attempt_count(self):
        target = hashlib.md5(b"no such word in the list 424242").hexdigest()
        result = hc.crack_hash(target)
        self.assertFalse(result["found"])
        self.assertEqual(result["status"], "not_found")
        self.assertEqual(result["attempts"], len(hc.DEFAULT_WORDLIST))

    def test_identified_but_unsupported_formats_stop_cleanly(self):
        for value in ("$5$saltstring$abc", "$1$saltstring$abc"):
            with self.subTest(value=value):
                result = hc.crack_hash(value)
                self.assertEqual(result["status"], "unsupported_format")
                self.assertEqual(result["attempts"], 0)
                self.assertIn("not crackable", result["detail"])

    def test_invalid_bcrypt_target_is_reported(self):
        result = hc.crack_hash("$2b$notavalidbcryptvalue")
        self.assertEqual(result["status"], "invalid_target")


class GenSamplesTests(unittest.TestCase):
    def test_samples_are_generated_hashed_and_reproducible(self):
        with tempfile.TemporaryDirectory() as tmp:
            first = hc.generate_samples(3, tmp)
            first_passwords = [s["password"] for s in first["samples"]]
            second = hc.generate_samples(3, tmp)
            second_passwords = [s["password"] for s in second["samples"]]
            stored = json.loads(Path(first["path"]).read_text(
                encoding="utf-8"))
        self.assertEqual(len(first["samples"]), 3)
        self.assertEqual(first_passwords, second_passwords)
        for sample in first["samples"]:
            password = sample["password"].encode("utf-8")
            self.assertEqual(sample["md5"],
                             hashlib.md5(password).hexdigest())
            self.assertEqual(sample["sha256"],
                             hashlib.sha256(password).hexdigest())
            self.assertEqual(sample["ntlm"], hc.ntlm_hex(sample["password"]))
            self.assertTrue(bcrypt.checkpw(
                password, sample["bcrypt"].encode("ascii")))
        self.assertEqual(stored["seed"], hc.SAMPLE_SEED)
        self.assertEqual(len(stored["samples"]), 3)


class BenchmarkTests(unittest.TestCase):
    def test_benchmark_measures_every_algorithm(self):
        payload = hc.benchmark(min_seconds=0.05)
        names = [row["algorithm"] for row in payload["results"]]
        self.assertEqual(
            names,
            ["md5", "sha1", "sha256", "sha512", "ntlm (pure-python MD4)",
             "bcrypt", "bcrypt", "sha512crypt ($6$)"])
        for row in payload["results"]:
            self.assertGreater(row["guesses"], 0)
            self.assertGreater(row["guesses_per_second"], 0)
        summary = payload["summary"]
        self.assertEqual(summary["cost4_to_cost12_theoretical_factor"], 256)
        self.assertGreater(summary["md5_per_second"],
                           summary["bcrypt_cost12_per_second"])
        self.assertGreater(summary["md5_vs_bcrypt12_factor"], 1)
        self.assertIn(hc.MD4_BACKEND, payload["results"][4]["parameter"])


class CliTests(unittest.TestCase):
    def test_crack_via_json_cli(self):
        target = hashlib.md5(b"password").hexdigest()
        out = io.StringIO()
        with redirect_stdout(out):
            code = hc.main(["--hash", target, "--json"])
        self.assertEqual(code, 0)
        payload = json.loads(out.getvalue())
        self.assertEqual(payload["md4_backend"], hc.MD4_BACKEND)
        crack = payload["cracks"][0]
        self.assertEqual(crack["status"], "cracked")
        self.assertEqual(crack["password"], "password")

    def test_no_arguments_prints_help(self):
        out = io.StringIO()
        with redirect_stdout(out):
            code = hc.main([])
        self.assertEqual(code, 0)
        self.assertIn("usage", out.getvalue().lower())


