class Sha512CryptTests(unittest.TestCase):
    """Published vectors from Drepper's SHA-crypt specification 0.6."""

    VECTORS = [
        ("$6$saltstring", "Hello world!",
         "$6$saltstring$svn8UoSVapNtMuq1ukKS4tPQd8iKwSMHWjl/O817G3uBnIFNjnQJ"
         "uesI68u4OTLiBFdcbYEdFCoEOfaS35inz1"),
        ("$6$rounds=10000$saltstringsaltstring", "Hello world!",
         "$6$rounds=10000$saltstringsaltst$OW1/O6BYHV6BcXZu8QVeXbDWra3Oeqh0sb"
         "HbbMCVNSnCM/UrjmM0Dp8vOuZeHBy/YTBmSK6H9qs/y3RnOaw5v."),
        ("$6$rounds=5000$toolongsaltstring", "This is just a test",
         "$6$rounds=5000$toolongsaltstrin$lQ8jolhgVRVhY4b5pZKaysCLi0QBxGoNeKQ"
         "zQ3glMhwllF7oGDZxUhx1yxdYcz/e1JSbq3y6JMxxl8audkUEm0"),
        ("$6$rounds=10$roundstoolow", "the minimum number is still observed",
         "$6$rounds=1000$roundstoolow$kUMsbe306n21p9R.FRkW3IGn.S9NPN0x50YhH1x"
         "hLsPuWGsUSklZt58jaTfF4ZEQpyUNGc0dqbpBYYBaHHrsX."),
    ]

    def test_published_vectors(self):
        for setting, password, expected in self.VECTORS:
            with self.subTest(setting=setting):
                self.assertEqual(hc.sha512_crypt_setting(password, setting),
                                 expected)

    def test_rounds_below_minimum_are_clamped_and_echoed(self):
        rounds, salt, emit = hc.parse_sha512crypt_setting("$6$rounds=10$abc")
        self.assertEqual(rounds, hc.CRYPT_ROUNDS_MIN)
        self.assertEqual(salt, "abc")
        self.assertTrue(emit)

    def test_setting_without_rounds_uses_default(self):
        rounds, salt, emit = hc.parse_sha512crypt_setting("$6$abc")
        self.assertEqual(rounds, hc.CRYPT_ROUNDS_DEFAULT)
        self.assertEqual(salt, "abc")
        self.assertFalse(emit)

    def test_checker_accepts_the_password_and_rejects_others(self):
        setting, password, expected = self.VECTORS[0]
        checker = hc.make_checker(expected, "sha512crypt")
        self.assertTrue(checker(password))
        self.assertFalse(checker("not the password"))

    def test_parse_roundtrip(self):
        rounds, salt, digest = hc.parse_sha512crypt(self.VECTORS[0][2])
        self.assertEqual(rounds, hc.CRYPT_ROUNDS_DEFAULT)
        self.assertEqual(salt, "saltstring")
        self.assertEqual(len(digest), 86)


