class DetectFormatTests(unittest.TestCase):
    def test_hex_digest_lengths(self):
        cases = {
            "a" * 32: "md5",
            "a" * 40: "sha1",
            "a" * 64: "sha256",
            "a" * 128: "sha512",
        }
        for value, expected in cases.items():
            with self.subTest(length=len(value)):
                self.assertEqual(hc.detect_format(value)[0], expected)

    def test_32_hex_is_md5_or_ntlm_and_says_so(self):
        fmt, note = hc.detect_format("5f4dcc3b5aa765d61d8327deb882cf99")
        self.assertEqual(fmt, "md5")
        self.assertIn("NTLM", note)

    def test_prefixed_formats(self):
        self.assertEqual(hc.detect_format("$2b$12$abcdef")[0], "bcrypt")
        self.assertEqual(hc.detect_format("$6$salt$digest")[0], "sha512crypt")
        self.assertEqual(hc.detect_format("$5$salt$digest")[0], "sha256crypt")
        self.assertEqual(hc.detect_format("$1$salt$digest")[0], "md5crypt")

    def test_unknown_shapes(self):
        self.assertEqual(hc.detect_format("a" * 33)[0], "unknown")
        self.assertEqual(hc.detect_format("not-a-hash")[0], "unknown")


class MD4Tests(unittest.TestCase):
    RFC_VECTORS = {
        b"": "31d6cfe0d16ae931b73c59d7e0c089c0",
        b"a": "bde52cb31de33e46245e05fbdbd6fb24",
        b"abc": "a448017aaf21d8525fc10ae87aa6729d",
        b"message digest": "d9130a8164549fe818874806e1c7014b",
        b"abcdefghijklmnopqrstuvwxyz": "d79e1c308aa5bbcdeea8ed63df412da9",
    }

    def test_backend_is_reported(self):
        self.assertIn(hc.MD4_BACKEND, ("hashlib", "pure-python"))

    def test_rfc1320_vectors_via_md4(self):
        for message, expected in self.RFC_VECTORS.items():
            with self.subTest(message=message):
                self.assertEqual(hc.md4(message).hex(), expected)

    def test_pure_python_md4_matches_rfc1320(self):
        for message, expected in self.RFC_VECTORS.items():
            with self.subTest(message=message):
                self.assertEqual(hc._md4_pure(message).hex(), expected)


